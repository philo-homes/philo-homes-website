#!/usr/bin/env node
// Copies the mobile app's 3D room viewer (the HTML page its WebView runs, in
// philo-homes-mobile src/components/Room3DViewerDemo1.tsx) into
// public/app-viewer/viewer.html, so the website shows rooms and designs with
// exactly the app's viewer. Run it again whenever the app's viewer changes:
//
//   node scripts/sync-app-viewer.mjs ../philo-homes-mobile
//
// The page is the app's template literal, evaluated here. What the app fills
// in per render comes from the embedding page instead (src/components/AppViewer.tsx):
//   - sceneData / defaultRoom: window.parent.__appViewerInit[<id in ?id=>]
//   - window.ReactNativeWebView.postMessage: forwarded to the parent with postMessage
// Web-only change: the "Built room" toggle is hidden (see the end of this file).
// The app's imperative calls (injectJavaScript "window.fn(arg)") become direct
// calls on the iframe's window: the page is same-origin.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const mobile = resolve(process.argv[2] || '../philo-homes-mobile')
const viewerSrc = join(mobile, 'src/components/Room3DViewerDemo1.tsx')
const pbrSrc = join(mobile, 'src/components/pbrTextures.ts')
const out = join(dirname(fileURLToPath(import.meta.url)), '../public/app-viewer/viewer.html')

const src = readFileSync(viewerSrc, 'utf8')

// The three.js page: the template after "// Three.js GLB viewer code".
const marker = src.indexOf('// Three.js GLB viewer code')
const open = src.indexOf('const html = `', marker)
const close = src.indexOf('\n  `;\n', open)
if (marker < 0 || open < 0 || close < 0) throw new Error('viewer template not found: did Room3DViewerDemo1.tsx change shape?')
const body = src.slice(open + 'const html = `'.length, close + 3)

// PBR maps: `key:\n 'data:...',` pairs.
const PBR = {}
for (const m of readFileSync(pbrSrc, 'utf8').matchAll(/^\s*([a-z_]+):\s*'([^']+)'/gm)) PBR[m[1]] = m[2]
if (!PBR.floor_diff || !PBR.env_interior) throw new Error('PBR maps not found in pbrTextures.ts')

const dims = src.match(/const ROOM_DIMENSIONS = \{\s*length: ([\d.]+),\s*width: ([\d.]+),\s*height: ([\d.]+)/)
if (!dims) throw new Error('ROOM_DIMENSIONS not found')
const ROOM_DIMENSIONS = { length: +dims[1], width: +dims[2], height: +dims[3] }

// Tokens for what the embedding page supplies at run time.
const token = (name) => ({ toJSON: () => `@@${name}@@` })
const evaluate = new Function('PBR', 'ROOM_DIMENSIONS', 'defaultRoom', 'finalSceneData', 'modelUrl', 'dracoJs', `return \`${body}\``)
let html = evaluate(PBR, ROOM_DIMENSIONS, token('DEFAULT_ROOM'), token('SCENE_DATA'), '', false)

const replace = (from, to) => {
  if (!html.includes(from)) throw new Error(`expected ${from} in the viewer page`)
  html = html.split(from).join(to)
}
replace('"@@DEFAULT_ROOM@@"', '(window.__APP_VIEWER_INIT__.defaultRoom || null)')
replace('"@@SCENE_DATA@@"', '(window.__APP_VIEWER_INIT__.sceneData || null)')

const commit = (() => {
  try {
    return execFileSync('git', ['-C', mobile, 'log', '-1', '--format=%h %cs'], { encoding: 'utf8' }).trim()
  } catch {
    return 'unknown'
  }
})()

const bridge = `
    <!-- Generated by scripts/sync-app-viewer.mjs from philo-homes-mobile ${commit}
         (src/components/Room3DViewerDemo1.tsx). Do not edit by hand. -->
    <script>
      // The app's WebView bridge, for a same-origin iframe.
      (function () {
        var id = new URLSearchParams(location.search).get('id') || '';
        var init = {};
        try { init = (window.parent.__appViewerInit || {})[id] || {}; } catch (e) {}
        window.__APP_VIEWER_INIT__ = init;
        window.ReactNativeWebView = {
          postMessage: function (data) {
            try { window.parent.postMessage({ __appViewer: id, data: data }, location.origin); } catch (e) {}
          }
        };
      })();
    </script>`
replace('<head>', `<head>${bridge}`)

// Web-only: no "Built room" toggle. It swaps the room for a plain box the viewer
// builds itself, which customers took for a different room. The app keeps it.
replace('</head>', `<style>#room-mode { display: none !important; }</style>\n      </head>`)

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, html)
console.log(`wrote ${out} (${(html.length / 1024).toFixed(0)} KB) from philo-homes-mobile ${commit}`)
